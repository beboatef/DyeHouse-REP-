const dictionaries: Record<Lang, Record<string, string>> = { ar, en };

interface I18nContextValue {
  lang: Lang;
  dir: "rtl" | "ltr";
  isRtl: boolean;
  setLang: (lang: Lang) => void;
  t: (key: string, fallback?: string) => string;
  /** Picks the right side of a bilingual pair coming from the API (nameAr/nameEn). */
  pick: (arValue?: string | null, enValue?: string | null, fallback?: string | null) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);
const STORAGE_KEY = "dyehouse_lang";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const stored = typeof localStorage !== "undefined" ? localStorage.getItem(STORAGE_KEY) : null;
    return stored === "en" || stored === "ar" ? stored : "ar";
  });

  const dir: "rtl" | "ltr" = lang === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      // localStorage may be unavailable (private mode) - the switch still works for the session.
    }
  }, [lang, dir]);

  const t = useCallback(
    (key: string, fallback?: string) => dictionaries[lang][key] ?? dictionaries.ar[key] ?? fallback ?? key,
    [lang]
  );

  const pick = useCallback(
    (arValue?: string | null, enValue?: string | null, fallback?: string | null) => {
      const primary = lang === "ar" ? arValue : enValue;
      const secondary = lang === "ar" ? enValue : arValue;
      return primary || secondary || fallback || "";
    },
    [lang]
  );

  const value = useMemo<I18nContextValue>(
    () => ({ lang, dir, isRtl: dir === "rtl", setLang: setLangState, t, pick }),
    [lang, dir, t, pick]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used inside <I18nProvider> (see src/main.tsx).");
  }
  return context;
}
